import math
angle_degrees=45
angle_radian=math.radians(angle_degrees)
sine_value=math.sin(angle_radian)
print("This is the value of sine:", sine_value)
cosine_value=math.cos(angle_radian)
print("This is the value of cosine:", cosine_value)
tangent_value=math.tan(angle_radian)
print("This is the value of tangent:", tangent_value)